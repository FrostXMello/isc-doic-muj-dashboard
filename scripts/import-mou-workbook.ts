/**
 * Plans the import of the DoIC MoU register ("0_MoU details.xlsx") and writes
 * the reviewed artefacts. Touches no database.
 *
 *   npm run db:mou:plan
 *
 * Reads (gitignored):
 *   data/private/mou_details_structured.json   structured extraction (required)
 *   data/private/mou_details_all_data.json     raw extraction, cross-checked
 *   data/private/muj-nodal-contacts.json       existing nodal contacts
 *
 * Writes (gitignored; they hold internal contact data):
 *   data/private/mou-import-report.md          reconciliation report
 *   supabase/private/mou-workbook-import.sql   idempotent import, one transaction
 *   supabase/private/mou-workbook-rollback.sql removes exactly what the batch added
 *
 * Matching decisions live in scripts/mou-workbook/decisions.ts.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { todayISO } from "@/lib/internal/dates";
import { fieldLabel, sheetLabels, type SheetKey } from "@/lib/internal/workbook/source";
import { loadExisting } from "./mou-workbook/existing";
import { buildPlan, type Plan, untouchedAgreements, type Workbook } from "./mou-workbook/plan";
import { importSql, rollbackSql } from "./mou-workbook/sql";

const root = process.cwd();
const structuredPath = join(root, "data/private/mou_details_structured.json");
const rawPath = join(root, "data/private/mou_details_all_data.json");

if (!existsSync(structuredPath)) {
  console.error("Missing data/private/mou_details_structured.json");
  process.exit(1);
}

const workbook = JSON.parse(readFileSync(structuredPath, "utf8")) as Workbook;
const existing = loadExisting();
const plan = buildPlan(workbook, existing, todayISO());

// Cross-check the structured extraction against the raw one: every non-blank
// raw row below the header must appear as a record with the same Excel row.
const crossCheck: string[] = [];
if (existsSync(rawPath)) {
  const raw = JSON.parse(readFileSync(rawPath, "utf8")) as {
    worksheets: Record<string, { rows: { row: number; values: unknown[] }[] }>;
  };
  for (const [sheetName, sheet] of Object.entries(workbook.worksheets)) {
    const rawRows = raw.worksheets[sheetName]?.rows ?? [];
    const dataRows = rawRows.filter(
      (row) => row.row > sheet.header_excel_row && row.values.some((value) => value !== null && value !== ""),
    );
    const recordRows = new Set(sheet.records.map((record) => Number(record._source_excel_row)));
    const missing = dataRows.filter((row) => !recordRows.has(row.row)).map((row) => row.row);
    crossCheck.push(
      `${sheetName}: ${dataRows.length} non-blank raw rows, ${sheet.records.length} structured records` +
        (missing.length ? `; missing rows ${missing.join(", ")}` : "; every raw row is present"),
    );
  }
} else {
  crossCheck.push("Raw extraction not found; cross-check skipped.");
}

function report(plan: Plan) {
  const lines: string[] = [];
  const out = (line = "") => lines.push(line);
  const sheets = Object.keys(sheetLabels) as SheetKey[];
  const rowsOf = (sheet: SheetKey) => plan.rows.filter((row) => row.sheet === sheet);
  const statuses = ["matched", "created", "duplicate", "unresolved", "standalone"] as const;

  out("# DoIC MoU register — import reconciliation report");
  out();
  out("INTERNAL. Contains nodal officer names and contact details. Do not commit or share outside DoIC.");
  out();
  out(`Source: ${plan.sourceFile}. Batch: \`${plan.batch}\`. Generated by \`npm run db:mou:plan\`.`);
  out();
  out("## Source records");
  out();
  out("| Sheet | Records | Matched | Created | Duplicate | Unresolved | Standalone |");
  out("|---|---|---|---|---|---|---|");
  for (const sheet of sheets) {
    const rows = rowsOf(sheet);
    out(
      `| ${sheetLabels[sheet]} | ${rows.length} | ${statuses.map((status) => rows.filter((row) => row.matchStatus === status).length).join(" | ")} |`,
    );
  }
  out();
  out(
    `MoU Status has ${plan.counts["mou-status"]} records plus its header row, whose column B holds a university name; the header row is kept as its own source row.`,
  );
  out();
  for (const line of crossCheck) out(`- ${line}`);
  out();
  out("## What the import writes");
  out();
  out(`- Countries added: ${plan.countries.map((country) => country.name).join(", ") || "none"}.`);
  out(`- Universities added: ${plan.institutions.length} (internal only, not on the public site).`);
  out(
    `- Agreements: ${plan.agreements.filter((a) => a.existing).length} existing official rows enriched (only empty dates and a "not stated" status are filled), ${plan.agreements.filter((a) => !a.existing).length} added.`,
  );
  out(`- Agreement details: ${plan.agreements.length} rows (one per agreement from the MoU list).`);
  out(
    `- Contacts added: ${plan.contacts.length} (${["MUJ Nodal Officer", "MUJ Nodal Officer (earlier)", "Partner Nodal Officer"].map((role) => `${plan.contacts.filter((c) => c.roleLabel === role).length} ${role}`).join(", ")}).`,
  );
  out(
    `- Existing nodal contacts repeated by the register: ${plan.contactDuplicates.length} (not duplicated; ${plan.contactFills.length} had an empty phone or email filled).`,
  );
  out(`- Source rows: ${plan.rows.length}, each with its sheet and Excel row.`);
  out(`- Existing official agreements no register row maps to (unchanged): ${untouchedAgreements(plan, existing).length}.`);
  out();
  out("## Normalisation rules");
  out();
  out("Rules from src/lib/internal/workbook/source.ts:");
  out();
  out("1. A blank cell is \"not recorded\"; it is never shown as NA or None.");
  out("2. Placeholder text (NA, N/A, None, Nil, -, Not recorded) is kept and shown exactly as written; it never fills a date, year, status, phone, or email, and different placeholders are not merged.");
  out("3. Formula cells: serial numbers are ignored; any other formula's computed value is withheld and listed below.");
  out("4. Dates: ISO dates are used; DD/MM/YYYY text is read day-first (the header says DDMMYYYY); other text stays text. An expiry before signing is not used as a date.");
  out("5. Status: Active maps to stored status \"signed\" and Expired to \"signed\" only when an expiry date is recorded (the portal derives active/expired from the dates; without a date it stays \"not stated\"); Closed maps to \"terminated\". The recorded word is always kept, and a word that contradicts the dates is listed for review.");
  out("6. Phone numbers: whole numbers and phone-shaped text are stored; other text becomes a note; negative or fractional numbers (formula output) are withheld.");
  out("7. Emails: each valid address in a cell is kept (the first as the email, others in the note); invalid text is kept as a note and listed below.");
  out("8. Shifted rows: when the status column holds a person's name and a ranking column holds a status, only reference, name, year, period, signing, and expiry are used.");
  out("9. Nodal officers: the revised officer is the current one and receives the row's email and number; a different original officer is kept as \"earlier\" with name only. Several names in one cell stay together as recorded.");
  out();
  out("## New universities");
  out();
  for (const institution of plan.institutions) {
    out(`- \`${institution.slug}\` ${institution.name} (${institution.countryId}) — MoU list row ${institution.excelRow}.`);
  }
  out();
  out("## University matches other than exact names (reviewed decisions)");
  out();
  for (const row of plan.rows.filter((r) => r.matchNote?.startsWith("Reviewed match") || r.matchNote?.startsWith("New university"))) {
    out(`- ${sheetLabels[row.sheet]} row ${row.excelRow}: "${row.values[Object.keys(row.values).find((h) => /name|maharashtra|national collab/i.test(h)) ?? ""] ?? ""}" → ${row.institutionSlug ?? "—"}. ${row.matchNote}`);
  }
  out();
  out("## Agreement matches (MoU list)");
  out();
  out("| Row | DoIC reference | University | Agreement | Basis |");
  out("|---|---|---|---|---|");
  for (const agreement of [...plan.agreements].sort((a, b) => a.excelRow - b.excelRow)) {
    out(
      `| ${agreement.excelRow} | ${agreement.details.doicReference ?? "—"} | ${agreement.institutionSlug} | ${agreement.code}${agreement.existing ? "" : " (new)"} | ${agreement.needsReview ? "needs review" : agreement.existing ? "paired" : "new"} |`,
    );
  }
  out();
  out("## Duplicates");
  out();
  for (const row of plan.rows.filter((r) => r.matchStatus === "duplicate")) {
    out(`- MoU list row ${row.excelRow}: ${row.matchNote} ${row.issues.join(" ")}`);
  }
  for (const duplicate of plan.contactDuplicates) {
    out(`- Contact ${duplicate.code} (${duplicate.existing}) is repeated by MoU list row ${duplicate.excelRow}; kept once.`);
  }
  out();
  out("## Unresolved relationships");
  out();
  for (const row of plan.rows.filter((r) => r.matchStatus === "unresolved")) {
    out(`- ${sheetLabels[row.sheet]} row ${row.excelRow}: ${row.matchNote}`);
  }
  for (const row of plan.rows.filter((r) => r.institutionSlug && !r.agreementCode && r.sheet !== "mou-list")) {
    out(`- ${sheetLabels[row.sheet]} row ${row.excelRow} (${row.institutionSlug}): ${row.matchNote}`);
  }
  for (const agreement of untouchedAgreements(plan, existing)) {
    const institutionRows = plan.agreements.filter((a) => a.institutionSlug === agreement.institutionSlug);
    if (institutionRows.length > 0) {
      out(
        `- Official row ${agreement.code} ("${agreement.title}") was not paired with a register row, although the register lists ${institutionRows.map((a) => `row ${a.excelRow}`).join(", ")} for the same university. Confirm whether it is the same agreement.`,
      );
    }
  }
  out();
  out("## Records requiring manual review");
  out();
  for (const row of plan.rows.filter((r) => r.issues.length > 0)) {
    out(`- ${sheetLabels[row.sheet]} row ${row.excelRow}:`);
    for (const issue of row.issues) out(`  - ${issue}`);
  }
  out();
  out("## Columns kept only in the source rows");
  out();
  out(
    `Country and continent stay on the source row; the university's country decides its portal region. The MoU Status sheet's nodal officer cell (name and number in one cell) is shown with the workflow, not as a contact. National MoUs columns D–H are unlabelled and shown as "${fieldLabel("Column_F")}" and so on.`,
  );
  return `${lines.join("\n")}\n`;
}

mkdirSync(join(root, "supabase/private"), { recursive: true });
writeFileSync(join(root, "data/private/mou-import-report.md"), report(plan));
writeFileSync(join(root, "supabase/private/mou-workbook-import.sql"), importSql(plan));
writeFileSync(join(root, "supabase/private/mou-workbook-rollback.sql"), rollbackSql(plan));

const tally = (status: string) => plan.rows.filter((row) => row.matchStatus === status).length;
console.log(
  `Planned ${plan.rows.length} source rows: ${tally("matched")} matched, ${tally("created")} created, ${tally("duplicate")} duplicate, ${tally("unresolved")} unresolved, ${tally("standalone")} standalone.`,
);
console.log(
  `${plan.institutions.length} new universities, ${plan.agreements.filter((a) => !a.existing).length} new and ${plan.agreements.filter((a) => a.existing).length} enriched agreements, ${plan.contacts.length} contacts.`,
);
if (plan.proposals.length > 0) {
  console.log(`${plan.proposals.length} names need a decision in scripts/mou-workbook/decisions.ts (see the report).`);
}
console.log("Wrote data/private/mou-import-report.md and supabase/private/mou-workbook-{import,rollback}.sql");
