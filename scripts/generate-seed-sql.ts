type SqlValue = string | number | boolean | null | undefined;

function lit(value: SqlValue): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${value.replace(/'/g, "''")}'`;
}

function slugify(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function ref(table: string, column: string, key: string | null | undefined) {
  return key ? `(select id from public.${table} where ${column} = ${lit(key)})` : "null";
}

type Row = Record<string, string>;

function insert(table: string, row: Row) {
  const columns = Object.keys(row);
  return `insert into public.${table} (${columns.join(", ")})\nvalues (${columns
    .map((column) => row[column])
    .join(", ")});`;
}

/** Insert-or-update on a unique key, so the file can be loaded repeatedly. */
function upsert(table: string, conflict: string, row: Row) {
  const columns = Object.keys(row);
  const updates = columns
    .filter((column) => column !== conflict)
    .map((column) => `  ${column} = excluded.${column}`);
  return `${insert(table, row).slice(0, -1)}\non conflict (${conflict}) do update set\n${updates.join(",\n")};`;
}

function provenance(record: Provenance): Row {
  return {
    source_url: lit(record.sourceUrl),
    source_title: lit(record.sourceTitle),
    source_checked_on: lit(record.sourceCheckedOn),
    verification: lit(record.verification),
  };
}

function header(title: string, notes: string[]) {
  return [
    `-- ${title}`,
    "-- GENERATED by scripts/generate-seed-sql.ts. Do not edit by hand;",
    "-- run `npm run db:seed:generate` instead.",
    ...notes.map((note) => `-- ${note}`),
    "",
  ].join("\n");
}

const allCountries = [...officialCountries, ...referenceCountries];
const countrySlugByName = new Map(allCountries.map((country) => [country.name, country.id]));

function countrySlug(name: string) {
  const slug = countrySlugByName.get(name);
  if (!slug) throw new Error(`No country row for "${name}"`);
  return slug;
}

