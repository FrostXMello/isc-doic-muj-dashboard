// Private: nodal officer contacts (internal-only, gitignored)
// ---------------------------------------------------------------------------

type PrivateContacts = {
  sourceUrl: string;
  checkedOn: string;
  contacts: {
    agreementId: string;
    roleLabel: string;
    name: string | null;
    phone: string | null;
    email: string | null;
  }[];
};

const root = process.cwd();
const contactsJson = join(root, "data", "private", "muj-nodal-contacts.json");
let contacts: string[] | null = null;

if (existsSync(contactsJson)) {
  const input = JSON.parse(readFileSync(contactsJson, "utf8")) as PrivateContacts;
  const institutionByAgreement = new Map(
    officialAgreementRecords.map((agreement) => [agreement.id, agreement.institutionId]),
  );
  contacts = [
    header("INTERNAL-ONLY nodal officer contacts. NEVER COMMIT THIS FILE.", [
      "From the official partner page; stored in public.institution_contacts",
      "with visibility 'internal' (readable by internal roles only).",
      "Requires 01_official.sql first. Idempotent.",
    ]),
  ];
  for (const contact of input.contacts) {
    const institutionId = institutionByAgreement.get(contact.agreementId);
    if (!institutionId) throw new Error(`Contact for unknown agreement ${contact.agreementId}`);
    if (!contact.name && !contact.phone && !contact.email) continue;
    contacts.push(
      upsert("institution_contacts", "code", {
        code: lit(`nc-${contact.agreementId}`),
        institution_id: ref("institutions", "slug", institutionId),
        agreement_id: ref("agreements", "code", contact.agreementId),
        role_label: lit(contact.roleLabel),
        full_name: lit(contact.name),
        phone: lit(contact.phone),
        email: lit(contact.email),
        visibility: lit("internal"),
        data_source: lit("official"),
        source_url: lit(input.sourceUrl),
        source_title: lit(officialSources.partners.title),
        source_checked_on: lit(input.checkedOn),
        verification: lit("source-imported"),
      }),
    );
  }
}

