// ---------------------------------------------------------------------------

function write(relative: string, statements: string[]) {
  const path = join(root, relative);
  mkdirSync(join(path, ".."), { recursive: true });
  writeFileSync(path, `${statements.join("\n\n")}\n`);
  console.log(`wrote ${relative} (${statements.length - 1} statements)`);
}

write("supabase/seeds/01_official.sql", official);
write("supabase/seeds/02_directory.sql", directory);
write("supabase/seeds/03_sample.sql", sample);
if (contacts) {
  write("supabase/private/muj-nodal-contacts.sql", contacts);
} else {
  console.log("skipped supabase/private/muj-nodal-contacts.sql (data/private/muj-nodal-contacts.json not found)");
}
