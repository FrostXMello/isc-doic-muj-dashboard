const sample: string[] = [
  header("FICTIONAL SAMPLE DATA for the internal portal workflow.", [
    "LOCAL DEVELOPMENT ONLY. Loaded by `supabase db reset`; never load into a",
    "hosted project (do not use `supabase db push --include-seed`).",
    "Every row is data_source = 'sample' and never public.",
  ]),
];

for (const institution of sampleInstitutions) {
  sample.push(insert("institutions", institutionRow(institution)));
}

const areaNames = [...new Set(agreementSeed.flatMap((agreement) => agreement.collaborationAreas))];
for (const name of areaNames) {
  sample.push(
    insert("collaboration_areas", {
      slug: lit(slugify(name)),
      name: lit(name),
      data_source: lit("sample"),
    }),
  );
}

for (const agreement of agreementSeed) {
  sample.push(insert("agreements", agreementRow(agreement)));
  agreement.collaborationAreas.forEach((name, position) => {
    sample.push(
      insert("agreement_collaboration_areas", {
        agreement_id: ref("agreements", "code", agreement.id),
        collaboration_area_id: ref("collaboration_areas", "slug", slugify(name)),
        position: lit(position),
      }),
    );
  });
}
for (const offering of availabilitySeed) sample.push(insert("program_availability", availabilityRow(offering)));
for (const opportunity of opportunitySeed) sample.push(insert("opportunities", opportunityRow(opportunity)));
for (const document of documentSeed) sample.push(insert("documents", documentRow(document)));
for (const link of documentLinkSeed) sample.push(insert("document_links", documentLinkRow(link)));
for (const activity of activitySeed) sample.push(insert("activities", activityRow(activity)));

sample.push(
  "-- Seed inserts are not user activity; start local development with an empty audit log.",
  "truncate public.audit_logs restart identity;",
);

