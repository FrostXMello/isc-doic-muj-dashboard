function institutionRow(institution: Institution): Row {
  return {
    slug: lit(institution.id),
    name: lit(institution.name),
    normalized_name: lit(institution.normalizedName),
    country_id: ref("countries", "slug", institution.countryId),
    city: lit(institution.city),
    latitude: lit(institution.latitude),
    longitude: lit(institution.longitude),
    location_verified: lit(false),
    website: lit(institution.website),
    note: lit(institution.note),
    is_public: lit(institution.isPublic && institution.source === "official"),
    data_source: lit(institution.source),
    ...provenance(institution),
  };
}

const sourceRowById = new Map(officialAgreementRows.map((row) => [row.id, row.sourceRow]));

function agreementRow(agreement: Agreement): Row {
  return {
    code: lit(agreement.id),
    reference: lit(agreement.reference),
    institution_id: ref("institutions", "slug", agreement.institutionId),
    title: lit(agreement.title),
    agreement_type: lit(agreement.type),
    type_label: lit(agreement.typeLabel),
    record_status: lit(agreement.recordStatus),
    start_date: lit(agreement.startDate),
    end_date: lit(agreement.endDate),
    renewal: lit(agreement.renewal),
    notes: lit(agreement.notes),
    source_section: lit(agreement.sourceSection),
    source_row: lit(sourceRowById.get(agreement.id)),
    is_public_summary: lit(agreement.source === "official"),
    data_source: lit(agreement.source),
    ...provenance(agreement),
  };
}

function availabilityRow(offering: ProgramAvailability): Row {
  return {
    code: lit(offering.id),
    program_id: ref("programs", "program_type", offering.programId),
    institution_id: ref("institutions", "slug", offering.institutionId),
    agreement_id: ref("agreements", "code", offering.agreementId),
    availability: lit(offering.availability),
    duration: lit(offering.duration),
    intake: lit(offering.intake),
    application_start: lit(offering.applicationStart),
    application_end: lit(offering.applicationEnd),
    eligibility: lit(offering.eligibility),
    credit_information: lit(offering.creditInformation),
    notes: lit(offering.notes),
    is_published: lit(offering.source === "official"),
    data_source: lit(offering.source),
    ...provenance(offering),
  };
}

function opportunityRow(opportunity: Opportunity): Row {
  return {
    code: lit(opportunity.id),
    title: lit(opportunity.title),
    program_id: ref("programs", "program_type", opportunity.programId),
    availability_id: ref("program_availability", "code", opportunity.availabilityId),
    institution_id: ref("institutions", "slug", opportunity.institutionId),
    opens_on: lit(opportunity.opensOn),
    deadline: lit(opportunity.deadline),
    record_status: lit(opportunity.recordStatus),
    summary: lit(opportunity.summary),
    data_source: lit(opportunity.source),
    ...provenance(opportunity),
  };
}

function documentRow(document: DocumentRecord): Row {
  return {
    code: lit(document.id),
    title: lit(document.title),
    document_type: lit(document.type),
    status: lit(document.status),
    revised_on: lit(document.updatedOn),
    description: lit(document.description),
    external_url: lit(document.url),
    publicly_accessible: lit(document.publiclyAccessible),
    data_source: lit(document.source),
    ...provenance(document),
  };
}

function documentLinkRow(link: DocumentLink): Row {
  return {
    code: lit(link.id),
    document_id: ref("documents", "code", link.documentId),
    institution_id: ref("institutions", "slug", link.institutionId),
    agreement_id: ref("agreements", "code", link.agreementId),
    program_id: ref("programs", "program_type", link.programId),
    availability_id: ref("program_availability", "code", link.availabilityId),
  };
}

function activityRow(activity: Activity): Row {
  return {
    code: lit(activity.id),
    title: lit(activity.title),
    activity_type: lit(activity.type),
    record_status: lit(activity.recordStatus),
    start_date: lit(activity.startDate),
    end_date: lit(activity.endDate),
    country_id: ref("countries", "slug", countrySlug(activity.country)),
    city: lit(activity.city),
    institution_id: ref("institutions", "slug", activity.institutionId),
    agreement_id: ref("agreements", "code", activity.agreementId),
    summary: lit(activity.summary),
    participants: lit(activity.participants),
    data_source: lit(activity.source),
    ...provenance(activity),
  };
}

