/**
 * SQL for a register import plan. The import is one transaction that:
 *  - stops unless migration 20261013090000 is applied and every existing
 *    university, agreement, and contact the plan relies on is present;
 *  - never overwrites: existing agreements only get empty dates and a
 *    "not stated" status filled, inserts skip rows that already exist, and
 *    source rows keep any match an administrator has corrected;
 *  - records each insert, and the previous state of each changed row, in
 *    private.workbook_import_ledger, which the rollback reads.
 * Running it again changes nothing.
 */

import type { Plan } from "./plan";

type SqlValue = string | number | boolean | null | undefined;

export function lit(value: SqlValue): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error("Non-finite number in SQL");
    return String(value);
  }
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${value.replace(/'/g, "''")}'`;
}

const date = (value: string | null) => (value ? `date ${lit(value)}` : "null");
const json = (value: unknown) => `${lit(JSON.stringify(value))}::jsonb`;

function ledger(plan: Plan, table: string, operation: "insert" | "update", source: string) {
  return (
    `insert into private.workbook_import_ledger (import_batch, table_name, record_id, operation${operation === "update" ? ", previous" : ""})\n` +
    `select ${lit(plan.batch)}, ${lit(table)}, ${source}\n` +
    "on conflict on constraint workbook_import_ledger_entry_key do nothing;"
  );
}

function sourceTitle(plan: Plan, sheet: string, row: number) {
  return `DoIC MoU register (${plan.sourceFile}), ${sheet} row ${row}`;
}

export function importSql(plan: Plan): string {
  if (plan.proposals.length > 0) {
    throw new Error(`${plan.proposals.length} names have no reviewed decision; resolve them before generating SQL.`);
  }
  const out: string[] = [];
  const push = (...lines: string[]) => out.push(...lines, "");
  const institutionRef = (slug: string) => `(select id from public.institutions where slug = ${lit(slug)})`;
  const agreementRef = (code: string) => `(select id from public.agreements where code = ${lit(code)})`;

  push(
    "-- INTERNAL: DoIC MoU register import. Contains nodal officer contact details. NEVER COMMIT.",
    "-- Generated by scripts/import-mou-workbook.ts (npm run db:mou:plan). Do not edit by hand.",
    `-- Batch ${plan.batch}. Run: psql \"$DB_URL\" -v ON_ERROR_STOP=1 -f supabase/private/mou-workbook-import.sql`,
    "begin;",
  );

  // Preconditions.
  const expectedInstitutions = new Set<string>();
  for (const agreement of plan.agreements) {
    if (!plan.institutions.some((institution) => institution.slug === agreement.institutionSlug)) {
      expectedInstitutions.add(agreement.institutionSlug);
    }
  }
  for (const row of plan.rows) {
    if (row.institutionSlug && !row.institutionSlug.startsWith("wb-")) expectedInstitutions.add(row.institutionSlug);
  }
  const expected: [string, string][] = [
    ...[...expectedInstitutions].sort().map((slug) => ["institution", slug] as [string, string]),
    ...plan.agreements
      .filter((agreement) => agreement.existing)
      .map((agreement) => ["agreement", `${agreement.code}@${agreement.institutionSlug}`] as [string, string]),
    ...plan.contactDuplicates.map((duplicate) => ["contact", duplicate.code] as [string, string]),
    ...[...new Set(plan.institutions.map((institution) => institution.countryId))]
      .filter((country) => !plan.countries.some((added) => added.slug === country))
      .map((country) => ["country", country] as [string, string]),
  ];
  push(
    "do $$",
    "begin",
    "  if to_regclass('public.source_workbook_rows') is null or to_regclass('private.workbook_import_ledger') is null then",
    "    raise exception 'Apply migration 20261013090000_mou_workbook.sql first';",
    "  end if;",
    "end;",
    "$$;",
    "create temporary table wb_expected (kind text not null, key text not null) on commit drop;",
    `insert into wb_expected (kind, key) values\n${expected.map(([kind, key]) => `  (${lit(kind)}, ${lit(key)})`).join(",\n")};`,
    "do $$",
    "declare",
    "  missing text;",
    "begin",
    "  select string_agg(e.kind || ' ' || e.key, ', ') into missing",
    "  from wb_expected e",
    "  where (e.kind = 'institution' and not exists (select 1 from public.institutions i where i.slug = e.key))",
    "     or (e.kind = 'agreement' and not exists (",
    "       select 1 from public.agreements a join public.institutions i on i.id = a.institution_id",
    "       where a.code = split_part(e.key, '@', 1) and i.slug = split_part(e.key, '@', 2)))",
    "     or (e.kind = 'contact' and not exists (select 1 from public.institution_contacts c where c.code = e.key))",
    "     or (e.kind = 'country' and not exists (select 1 from public.countries c where c.slug = e.key and c.region_id is not null));",
    "  if missing is not null then",
    "    raise exception 'Import stopped: this database is missing %', missing;",
    "  end if;",
    "end;",
    "$$;",
  );

  // Countries.
  for (const country of plan.countries) {
    push(
      `-- Country: ${country.name}`,
      "with added as (",
      "  insert into public.countries (slug, name, iso2, region_id, is_public, data_source)",
      `  select ${lit(country.slug)}, ${lit(country.name)}, ${lit(country.iso2)}, r.id, false, 'official'`,
      `  from public.regions r where r.name = ${lit(country.region)}`,
      "  on conflict do nothing",
      "  returning id",
      ")",
      ledger(plan, "countries", "insert", "id, 'insert' from added"),
    );
  }

  // Universities.
  for (const institution of plan.institutions) {
    push(
      `-- University: ${institution.name}`,
      "with added as (",
      "  insert into public.institutions (slug, name, normalized_name, country_id, is_public, data_source, note, source_title, verification)",
      `  select ${lit(institution.slug)}, ${lit(institution.name)}, ${lit(institution.normalizedName)}, c.id, false, 'official', ${lit(institution.note)}, ${lit(sourceTitle(plan, "MoU list", institution.excelRow))}, 'source-imported'`,
      `  from public.countries c where c.slug = ${lit(institution.countryId)}`,
      "  on conflict do nothing",
      "  returning id",
      ")",
      ledger(plan, "institutions", "insert", "id, 'insert' from added"),
    );
  }

  // Agreements.
  for (const agreement of plan.agreements) {
    const fill = agreement.fill;
    const verification = agreement.needsReview ? "needs-review" : "source-imported";
    if (agreement.existing) {
      const sets = [
        fill.startDate ? `start_date = coalesce(start_date, ${date(fill.startDate)})` : null,
        fill.endDate ? `end_date = coalesce(end_date, ${date(fill.endDate)})` : null,
        fill.recordStatus
          ? `record_status = case when record_status = 'not-stated' then ${lit(fill.recordStatus)}::public.agreement_record_status else record_status end`
          : null,
      ].filter(Boolean);
      push(`-- Agreement ${agreement.code} (MoU list row ${agreement.excelRow})`);
      if (sets.length > 0) {
        push(
          ledger(
            plan,
            "agreements",
            "update",
            `a.id, 'update', to_jsonb(a) from public.agreements a where a.code = ${lit(agreement.code)}`,
          ),
          `update public.agreements set ${sets.join(", ")}`,
          `where code = ${lit(agreement.code)};`,
        );
      }
    } else {
      push(
        `-- New agreement ${agreement.code} (MoU list row ${agreement.excelRow})`,
        "with added as (",
        "  insert into public.agreements (code, reference, institution_id, title, agreement_type, type_label, record_status, start_date, end_date, data_source, source_title, verification)",
        `  values (${lit(agreement.code)}, ${lit(agreement.reference)}, ${institutionRef(agreement.institutionSlug)}, ${lit(agreement.title)}, ${lit(agreement.type)}, ${lit(agreement.typeLabel)}, ${lit(fill.recordStatus ?? "not-stated")}, ${date(fill.startDate)}, ${date(fill.endDate)}, 'official', ${lit(sourceTitle(plan, "MoU list", agreement.excelRow))}, ${lit(verification)})`,
        "  on conflict do nothing",
        "  returning id",
        ")",
        ledger(plan, "agreements", "insert", "id, 'insert' from added"),
      );
    }
    const d = agreement.details;
    push(
      "with added as (",
      "  insert into public.agreement_details (agreement_id, doic_reference, initiation_year, renewal_year, period_text, expiry_text, recorded_status, qs_ranking, the_ranking, faculty, department, opportunities, programme_reference, remarks, document_url)",
      `  values (${agreementRef(agreement.code)}, ${[d.doicReference, d.initiationYear, d.renewalYear, d.periodText, d.expiryText, d.recordedStatus, d.qsRanking, d.theRanking, d.faculty, d.department, d.opportunities, d.programmeReference, d.remarks, d.documentUrl].map(lit).join(", ")})`,
      "  on conflict (agreement_id) do nothing",
      "  returning agreement_id",
      ")",
      ledger(plan, "agreement_details", "insert", "agreement_id, 'insert' from added"),
    );
  }

  // Contacts.
  for (const contact of plan.contacts) {
    push(
      "with added as (",
      "  insert into public.institution_contacts (code, institution_id, agreement_id, role_label, full_name, phone, email, source_note, visibility, data_source, source_title, verification)",
      `  values (${lit(contact.code)}, ${institutionRef(contact.institutionSlug)}, ${agreementRef(contact.agreementCode)}, ${lit(contact.roleLabel)}, ${lit(contact.name)}, ${lit(contact.phone)}, ${lit(contact.email)}, ${lit(contact.note)}, 'internal', 'official', ${lit(sourceTitle(plan, "MoU list", contact.excelRow))}, 'source-imported')`,
      "  on conflict do nothing",
      "  returning id",
      ")",
      ledger(plan, "institution_contacts", "insert", "id, 'insert' from added"),
    );
  }
  for (const fill of plan.contactFills) {
    const sets = [
      fill.phone ? `phone = coalesce(phone, ${lit(fill.phone)})` : null,
      fill.email ? `email = coalesce(email, ${lit(fill.email)})` : null,
    ].filter(Boolean);
    push(
      ledger(
        plan,
        "institution_contacts",
        "update",
        `c.id, 'update', to_jsonb(c) from public.institution_contacts c where c.code = ${lit(fill.code)}`,
      ),
      `update public.institution_contacts set ${sets.join(", ")} where code = ${lit(fill.code)};`,
    );
  }

  // Source rows.
  for (const row of plan.rows) {
    push(
      "with upserted as (",
      "  insert into public.source_workbook_rows as t (import_key, workbook, sheet, excel_row, source_values, source_formulas, issues, institution_id, agreement_id, match_status, match_note, import_batch)",
      `  values (${lit(row.importKey)}, ${lit(plan.sourceFile)}, ${lit(row.sheet)}, ${row.excelRow}, ${json(row.values)}, ${json(row.formulas)}, ${row.issues.length ? `array[${row.issues.map(lit).join(", ")}]::text[]` : "'{}'::text[]"}, ${row.institutionSlug ? institutionRef(row.institutionSlug) : "null"}, ${row.agreementCode ? agreementRef(row.agreementCode) : "null"}, ${lit(row.matchStatus)}, ${lit(row.matchNote)}, ${lit(plan.batch)})`,
      "  on conflict (import_key) do update set",
      "    source_values = excluded.source_values,",
      "    source_formulas = excluded.source_formulas,",
      "    issues = excluded.issues,",
      "    institution_id = coalesce(t.institution_id, excluded.institution_id),",
      "    agreement_id = coalesce(t.agreement_id, excluded.agreement_id),",
      "    match_status = case when t.institution_id is null and t.agreement_id is null then excluded.match_status else t.match_status end,",
      "    match_note = case when t.institution_id is null and t.agreement_id is null then excluded.match_note else t.match_note end",
      "  returning id, (xmax = 0) as inserted",
      ")",
      ledger(plan, "source_workbook_rows", "insert", "id, 'insert' from upserted where inserted"),
    );
  }

  push(
    "-- Summary",
    `select table_name, operation, count(*) from private.workbook_import_ledger where import_batch = ${lit(plan.batch)} group by 1, 2 order by 1, 2;`,
    "commit;",
  );
  return out.join("\n");
}

export function rollbackSql(plan: Plan): string {
  const batch = lit(plan.batch);
  const ids = (table: string, operation = "insert") =>
    `(select record_id from private.workbook_import_ledger where import_batch = ${batch} and table_name = '${table}' and operation = '${operation}')`;
  return [
    "-- INTERNAL: rolls back DoIC MoU register import batch " + plan.batch + ". NEVER COMMIT.",
    "-- Generated by scripts/import-mou-workbook.ts. Run: psql \"$DB_URL\" -v ON_ERROR_STOP=1 -f supabase/private/mou-workbook-rollback.sql",
    "-- Restores the agreement and contact values the import filled, then deletes what it",
    "-- inserted. Stops (and changes nothing) if records added since depend on them.",
    "begin;",
    "",
    "update public.agreements a set",
    "  start_date = (l.previous ->> 'start_date')::date,",
    "  end_date = (l.previous ->> 'end_date')::date,",
    "  record_status = (l.previous ->> 'record_status')::public.agreement_record_status",
    "from private.workbook_import_ledger l",
    `where l.import_batch = ${batch} and l.table_name = 'agreements' and l.operation = 'update' and l.record_id = a.id;`,
    "",
    "update public.institution_contacts c set",
    "  phone = l.previous ->> 'phone',",
    "  email = l.previous ->> 'email'",
    "from private.workbook_import_ledger l",
    `where l.import_batch = ${batch} and l.table_name = 'institution_contacts' and l.operation = 'update' and l.record_id = c.id;`,
    "",
    `delete from public.source_workbook_rows where id in ${ids("source_workbook_rows")};`,
    `delete from public.institution_contacts where id in ${ids("institution_contacts")};`,
    `delete from public.agreement_details where agreement_id in ${ids("agreement_details")};`,
    `delete from public.agreements where id in ${ids("agreements")};`,
    `delete from public.institutions where id in ${ids("institutions")};`,
    `delete from public.countries where id in ${ids("countries")};`,
    `delete from private.workbook_import_ledger where import_batch = ${batch};`,
    "",
    "commit;",
    "",
  ].join("\n");
}
